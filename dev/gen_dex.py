"""DEV ONLY. Writes lua/autorun/05_dex.lua from Showdown's data.

    curl -o pokedex.json https://play.pokemonshowdown.com/data/pokedex.json
    curl -o gen8.ts https://raw.githubusercontent.com/smogon/pokemon-showdown/master/data/mods/gen8/pokedex.ts
    python3 dev/gen_dex.py pokedex.json gen8.ts lua/autorun/05_dex.lua

pokedex.json holds the CURRENT generation's stats; gen8.ts is Showdown's list
of what was different in Gen 8 (Sword/Shield), applied on top.
"""
import json, sys, unicodedata, re
src, gen8, out = sys.argv[1], sys.argv[2], sys.argv[3]
dex = json.load(open(src, encoding='utf-8'))
# id -> Gen 8 base stats, where they differ from today's.
STAT = r'(\w+):\s*\{[^{}]*?baseStats:\s*\{\s*hp:\s*(\d+),\s*atk:\s*(\d+),\s*def:\s*(\d+),\s*spa:\s*(\d+),\s*spd:\s*(\d+),\s*spe:\s*(\d+)'
old = {m[0]: dict(zip(('hp', 'atk', 'def', 'spa', 'spd', 'spe'), map(int, m[1:])))
       for m in re.findall(STAT, open(gen8, encoding='utf-8').read())}
def key(n):
    n = unicodedata.normalize('NFKD', n).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]', '', n)
base, galar = {}, {}
for e in dex.values():
    if not (1 <= e.get('num', 0) <= 898) or e.get('isNonstandard') in ('CAP', 'Custom'):
        continue
    f = e.get('forme')
    if f is None: base[key(e['name'])] = e
    elif f == 'Galar': galar[key(e['baseSpecies'])] = e
rows = []
for k, e in sorted(base.items(), key=lambda kv: kv[1]['num']):
    g = galar.get(k)
    use = g or e
    s = old.get(key(use['name']), use['baseStats'])
    name = unicodedata.normalize('NFKD', e['name'].replace('’', "'")).encode('ascii', 'ignore').decode()
    rows.append('    %-14s = { %-22s %-20s %3d, %3d, %3d, %3d, %3d, %3d%s },' % (
        k if re.match(r'^[a-z]\w*$', k) else '["%s"]' % k,
        json.dumps(name) + ',',
        json.dumps('/'.join(use['types'])) + ',',
        s['hp'], s['atk'], s['def'], s['spa'], s['spd'], s['spe'],
        ', galar = true' if g else ''))
hdr = '''-- Gen 8 (Sword/Shield) base stats for every Pokemon up to #898, from Pokemon
-- Showdown's data: pokedex.json (today's stats) with its gen8 mod's
-- differences applied (Cresselia, Zacian, Zamazenta were changed in Gen 9).
-- Generated by dev/gen_dex.py -- don't edit by hand.
--
-- Keyed by the name in lower case, letters and digits only ("farfetchd",
-- "mrmime", "flabebe"), so an OCR reading is a direct lookup after the same
-- folding (SWSH.dexKey). Where a species has a Galarian form, that form's
-- types and stats are used (galar = true): it's the one met in Galar. Names
-- are plain ASCII for the overlay's built-in font.
--   key = { name, types, hp, atk, def, spa, spd, spe [, galar = true] }

SWSH = SWSH or {}

SWSH.DEX = {
'''
open(out, 'w', encoding='utf-8', newline='\n').write(hdr + '\n'.join(rows) + '\n}\n')
print(len(rows), 'species,', len(galar), 'galar; gen 8 stats for:', ', '.join(sorted(old)))
